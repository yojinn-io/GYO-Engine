"""Generates src/unicode/DefaultIgnorable.cpp from Unicode's DerivedCoreProperties.txt.

The text Module skips Default_Ignorable_Code_Point characters (ZWJ, variation
selectors, ...) when it checks whether a font covers a grapheme (declaration
docs/architecture/target/v2/text-declaration.zh-Hant.md 5.4, Design Invariant
TX-5). The table is generated once from the Unicode data file and kept in the
repository; the build does not need the data file or this script.

    python3 generate_default_ignorable.py <DerivedCoreProperties.txt> <output .cpp>
"""

import hashlib
import re
import sys


def main():
    source, output = sys.argv[1], sys.argv[2]
    data = open(source, "rb").read()
    text = data.decode("utf-8")
    version = re.search(r"DerivedCoreProperties-(\d+\.\d+\.\d+)\.txt", text).group(1)
    ranges = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, prop = (part.strip() for part in line.split(";", 1))
        if prop != "Default_Ignorable_Code_Point":
            continue
        first, _, last = cps.partition("..")
        ranges.append((int(first, 16), int(last or first, 16)))
    ranges.sort()
    merged = []
    for first, last in ranges:
        if merged and first == merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], last)
        else:
            merged.append((first, last))
    digest = hashlib.sha256(data).hexdigest()
    rows = "\n".join(f"    {{0x{a:06X}, 0x{b:06X}}}," for a, b in merged)
    out = f"""// Generated by engine/modules/text/scripts/generate_default_ignorable.py; do not edit.
// Source: Unicode {version} DerivedCoreProperties.txt, SHA-256 {digest}.
// Unicode data is used under the Unicode License v3 (https://www.unicode.org/license.txt).
#include "unicode/DefaultIgnorable.hpp"

#include <algorithm>
#include <array>

namespace GYO::Engine::Text::Detail {{

namespace {{

struct Range {{
    char32_t first;
    char32_t last;
}};

constexpr std::array<Range, {len(merged)}> kDefaultIgnorable{{{{
{rows}
}}}};

}} // namespace

bool IsDefaultIgnorable(const char32_t cp) noexcept {{
    const auto it = std::upper_bound(kDefaultIgnorable.begin(), kDefaultIgnorable.end(), cp,
                                     [](const char32_t value, const Range& range) {{ return value < range.first; }});
    return it != kDefaultIgnorable.begin() && cp <= std::prev(it)->last;
}}

}} // namespace GYO::Engine::Text::Detail
"""
    open(output, "w", encoding="utf-8", newline="\n").write(out)


if __name__ == "__main__":
    main()
